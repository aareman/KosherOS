#!/usr/bin/env bash
# Install this repository's shared git hooks: the worktree-safe dispatcher
# (git-hook-dispatch.sh) over every stage devenv uses, pre-commit and
# pre-push, and over any other prek-generated shim found there, since every
# one of those carries a baked-in path to one checkout. Git keeps ONE hooks
# directory for a repository and all of its worktrees, so a hook must never
# name a checkout.
#
# The dev shell runs this on entry (devenv.nix); `just hooks` runs it by
# hand, for a checkout whose shell has not been entered or after another
# tool has overwritten a hook. Quiet when nothing changes; --verbose says
# where the hooks are and what state they are in.
#
#   scripts/install-hooks.sh [--verbose]
set -euo pipefail

verbose=""
[ "${1:-}" = "--verbose" ] && verbose=1
root="$(cd "$(dirname "$0")/.." && pwd)"
dispatcher="$root/scripts/git-hook-dispatch.sh"

common="$(git -C "$root" rev-parse --path-format=absolute --git-common-dir 2>/dev/null || true)"
if [ -z "$common" ] || [ ! -f "$dispatcher" ]; then
    [ -n "$verbose" ] && echo "not a git checkout; no hooks to install" >&2
    exit 0
fi
hooks="$common/hooks"
mkdir -p "$hooks"

for hook in "$hooks"/pre-commit "$hooks"/pre-push "$hooks"/*; do
    case "$hook" in *.sample|*.legacy) continue ;; esac
    case "$hook" in
        "$hooks/pre-commit"|"$hooks/pre-push") ;;
        *) { [ -f "$hook" ] && grep -q "File generated by prek" "$hook"; } || continue ;;
    esac
    if ! cmp -s "$dispatcher" "$hook"; then
        install -m 755 "$dispatcher" "$hook"
        echo "installed the shared $(basename "$hook") hook into $hooks"
    fi
done
# prek keeps a hook it replaced as NAME.legacy and runs it afterwards; a
# copy of the dispatcher under that name would run everything twice.
for legacy in "$hooks"/*.legacy; do
    if [ -f "$legacy" ] && cmp -s "$dispatcher" "$legacy"; then
        rm -f "$legacy"
    fi
done

if [ -n "$verbose" ]; then
    echo "git hooks are in place in $hooks"
    if [ ! -f "$root/.pre-commit-config.yaml" ]; then
        echo "note: this checkout has no .pre-commit-config.yaml yet, so the"
        echo "      hooks will do nothing. Enter the dev shell to generate it."
    fi
fi
